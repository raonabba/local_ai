def prompt_guide(sections: tuple[str, ...] = ("principles", "structure", "words")) -> str:
    """프롬프트에 넣을 지침. 문맥이 짧으면 필요한 묶음만 고른다."""
    blocks = {
        "principles": ("[공문서 표현 원칙]", PRINCIPLES),
        "structure": ("[기안문 구성]", STRUCTURE),
        "words": ("[구별해서 쓸 말]", WORD_DISTINCTIONS),
    }
    out = []
    for key in sections:
        title, rules = blocks[key]
        out.append(title + "\n" + "\n".join(f"- {r}" for r in rules))
    return "\n\n".join(out)
